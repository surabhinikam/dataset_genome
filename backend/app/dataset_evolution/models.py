"""
backend/app/dataset_evolution/models.py — Pydantic v2 Schemas for Dataset Evolution Engine.

Defines EvolutionSeverity, EvolutionIssue, EvolutionRecommendation, and EvolutionPlan models.
"""

from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, ConfigDict


class EvolutionSeverity(str, Enum):
    """Severity classification for dataset gaps and weaknesses."""
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class EvolutionIssue(BaseModel):
    """Identified dataset quality gap, coverage flaw, or imbalance issue."""
    issue_id: str = Field(..., description="Unique slug for the issue (e.g. issue-cov-failure-01)")
    metric_name: str = Field(..., description="Metric key associated with the issue")
    current_value: float = Field(..., description="Current empirical value of the metric")
    target_threshold: float = Field(..., description="Target minimum threshold for healthy dataset")
    severity: EvolutionSeverity = Field(..., description="Assessed severity level: CRITICAL, HIGH, MEDIUM, LOW")
    description: str = Field(..., description="Human-readable explanation of why this is a dataset flaw")


class EvolutionRecommendation(BaseModel):
    """Prioritized actionable evolution recommendation for dataset enhancement."""
    recommendation_id: str = Field(..., description="Unique recommendation slug (e.g. rec-exp-clinical-01)")
    category: str = Field(..., description="Recommendation category (e.g. DOMAIN_EXPANSION, EXPERIMENT_DIVERSITY)")
    action_title: str = Field(..., description="Action title (e.g. Generate clinical trials, Generate missing scientific domains)")
    reason: str = Field(..., description="Detailed justification connecting back to identified issues")
    priority: int = Field(..., ge=1, description="1-indexed priority ranking (1 = highest priority)")
    severity: EvolutionSeverity = Field(..., description="Severity of the underlying issue being addressed")
    estimated_sample_count: int = Field(..., ge=1, description="Recommended number of new scientific samples to generate")
    expected_health_improvement: float = Field(..., ge=0.0, description="Projected increase to overall dataset health score (+points)")
    target_domain: Optional[str] = Field(None, description="Recommended target domain, if applicable")
    target_difficulty: Optional[str] = Field(None, description="Recommended target difficulty level, if applicable")


class EvolutionPlan(BaseModel):
    """
    Structured Dataset Evolution Plan generated by Evolution Planning Engine.
    """
    model_config = ConfigDict(arbitrary_types_allowed=True)

    plan_id: str = Field(..., description="Unique evolution plan slug")
    report_id: str = Field(..., description="ID of the underlying DatasetAnalysisReport")
    baseline_health_score: float = Field(..., ge=0.0, le=100.0, description="Initial overall dataset health score [0..100]")
    projected_health_score: float = Field(..., ge=0.0, le=100.0, description="Projected health score after executing evolution plan")
    total_recommended_samples: int = Field(..., ge=0, description="Total recommended sample volume to generate")
    issues: List[EvolutionIssue] = Field(default_factory=list, description="Ordered list of identified dataset issues")
    recommendations: List[EvolutionRecommendation] = Field(default_factory=list, description="Prioritized list of actionable recommendations")
    created_at: datetime = Field(default_factory=datetime.utcnow, description="Plan creation timestamp")
