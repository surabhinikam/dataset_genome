"""
backend/app/dataset_intelligence/models.py — Pydantic v2 Models for Dataset Intelligence.

Defines schemas for dataset statistics, coverage metrics, diversity metrics,
quality metrics, health scores, and DatasetAnalysisReport.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, ConfigDict


class GeneralStatistics(BaseModel):
    """General statistical breakdown of the dataset sample set."""
    total_samples: int = Field(..., ge=0, description="Total count of analyzed scientific records")
    domain_distribution: Dict[str, int] = Field(default_factory=dict, description="Sample count per scientific domain")
    difficulty_distribution: Dict[str, int] = Field(default_factory=dict, description="Sample count per difficulty level")
    average_prompt_length: float = Field(0.0, ge=0.0, description="Average character length of prompt fields")
    average_context_length: float = Field(0.0, ge=0.0, description="Average character length of context fields")


class ReasoningCoverageMetrics(BaseModel):
    """Coverage metrics across the 8 scientific reasoning steps (0.0 to 1.0 ratio)."""
    observation_coverage: float = Field(..., ge=0.0, le=1.0, description="Ratio of records with non-empty observation")
    problem_coverage: float = Field(..., ge=0.0, le=1.0, description="Ratio of records with non-empty identified_problem")
    research_gap_coverage: float = Field(..., ge=0.0, le=1.0, description="Ratio of records with non-empty research_gap")
    hypothesis_coverage: float = Field(..., ge=0.0, le=1.0, description="Ratio of records with non-empty primary_hypothesis")
    alternative_hypothesis_coverage: float = Field(..., ge=0.0, le=1.0, description="Ratio of records with non-empty alternative_hypothesis")
    experiment_design_coverage: float = Field(..., ge=0.0, le=1.0, description="Ratio of records with non-empty experiment_design")
    failure_case_coverage: float = Field(..., ge=0.0, le=1.0, description="Ratio of records with non-empty failure_cases list")
    scientific_conclusion_coverage: float = Field(..., ge=0.0, le=1.0, description="Ratio of records with non-empty scientific_conclusion")


class DiversityMetrics(BaseModel):
    """Diversity ratios and unique counts across domains, experiments, and metrics."""
    domain_diversity: float = Field(..., ge=0.0, le=1.0, description="Normalized domain entropy / unique domain ratio")
    experiment_diversity: float = Field(..., ge=0.0, le=1.0, description="Unique experiment design ratio")
    evaluation_metric_diversity: float = Field(..., ge=0.0, le=1.0, description="Unique evaluation metric vocabulary ratio")
    failure_case_diversity: float = Field(..., ge=0.0, le=1.0, description="Unique failure case vocabulary ratio")


class QualityMetrics(BaseModel):
    """Dataset structural quality, schema validity, and duplicate indicators."""
    dataset_completeness: float = Field(..., ge=0.0, le=1.0, description="Overall non-empty field completeness ratio")
    schema_consistency: float = Field(..., ge=0.0, le=1.0, description="Ratio of records fully adhering to schema")
    missing_field_count: int = Field(..., ge=0, description="Total aggregate count of missing or empty string/list fields")
    duplicate_sample_count: int = Field(..., ge=0, description="Count of duplicate or near-identical prompts/observations")


class DatasetHealthScores(BaseModel):
    """Normalized health scores (0–100 scale) for scientific dataset benchmarking."""
    knowledge_coverage_score: float = Field(..., ge=0.0, le=100.0, description="Normalized domain & reasoning coverage score [0..100]")
    reasoning_quality_score: float = Field(..., ge=0.0, le=100.0, description="Normalized reasoning step completeness & depth [0..100]")
    experiment_diversity_score: float = Field(..., ge=0.0, le=100.0, description="Normalized experimental setup diversity score [0..100]")
    scientific_completeness_score: float = Field(..., ge=0.0, le=100.0, description="Normalized schema & field completeness score [0..100]")
    overall_dataset_health_score: float = Field(..., ge=0.0, le=100.0, description="Composite weighted overall dataset health score [0..100]")


class DatasetAnalysisReport(BaseModel):
    """
    Comprehensive Dataset Quality Analysis Report generated by Dataset Intelligence Engine.
    """
    model_config = ConfigDict(arbitrary_types_allowed=True)

    report_id: str = Field(..., description="Unique analysis report slug")
    source_files: List[str] = Field(default_factory=list, description="List of analyzed JSONL dataset file paths")
    general_statistics: GeneralStatistics = Field(..., description="General statistical breakdown")
    reasoning_metrics: ReasoningCoverageMetrics = Field(..., description="Reasoning coverage metrics")
    diversity_metrics: DiversityMetrics = Field(..., description="Diversity metrics")
    quality_metrics: QualityMetrics = Field(..., description="Quality metrics")
    health_scores: DatasetHealthScores = Field(..., description="Normalized health scores (0-100)")
    analyzed_at: datetime = Field(default_factory=datetime.utcnow, description="Analysis timestamp")
