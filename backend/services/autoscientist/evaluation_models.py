"""
services/autoscientist/evaluation_models.py — Pydantic Schemas for Evaluation Engine.

Defines MetricDelta, EvaluationReport, EvaluateRequest, and EvaluateResponse.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
from uuid import UUID
from pydantic import BaseModel, Field, ConfigDict

from schemas.intelligence import GenomeReportResponse
from services.autoscientist.evaluation_constants import EvaluationOutcome, EvaluationRecommendation
from services.autoscientist.execution_models import ExecutionResult
from services.autoscientist.experiment_models import ExperimentPlan
from services.autoscientist.hypothesis_models import ScientificHypothesis


class MetricDelta(BaseModel):
    """Pairwise metric comparison delta between baseline and mutated datasets."""
    metric_name: str = Field(..., description="Name of the evaluated metric")
    value_before: float = Field(..., description="Baseline dataset metric value")
    value_after: float = Field(..., description="Mutated dataset metric value post execution")
    absolute_delta: float = Field(..., description="Signed absolute difference (value_after - value_before)")
    relative_delta_pct: float = Field(..., description="Relative percentage change")
    improved: bool = Field(..., description="Whether the change constitutes an improvement in quality")


class EvaluationReport(BaseModel):
    """
    Comprehensive Evaluation Report generated by the AutoScientist.
    
    Compares original vs transformed GenomeReport responses, verifies hypothesis claims,
    computes prediction errors, calibrates confidence, and produces actionable recommendations.
    """
    model_config = ConfigDict(arbitrary_types_allowed=True)

    evaluation_id: str = Field(..., description="Unique slug for the evaluation report")
    experiment_id: str = Field(..., description="ID of the evaluated experiment / plan")
    overall_result: EvaluationOutcome = Field(..., description="Overall verification outcome: VERIFIED, PARTIALLY_VERIFIED, FAILED")
    hypothesis_verified: bool = Field(..., description="True if hypothesis was verified or partially verified")
    predicted_improvement: float = Field(..., description="Predicted metric improvement delta from hypothesis")
    actual_improvement: float = Field(..., description="Actual observed metric improvement delta")
    prediction_error: float = Field(..., description="Absolute prediction error |predicted - actual|")
    metric_deltas: List[MetricDelta] = Field(default_factory=list, description="Categorical metric deltas breakdown")
    health_score_before: float = Field(..., ge=0.0, le=100.0, description="Baseline dataset overall health score [0..100]")
    health_score_after: float = Field(..., ge=0.0, le=100.0, description="Mutated dataset overall health score [0..100]")
    quality_score_before: float = Field(..., ge=0.0, le=1.0, description="Baseline normalized quality score [0..1]")
    quality_score_after: float = Field(..., ge=0.0, le=1.0, description="Mutated normalized quality score [0..1]")
    recommendation: EvaluationRecommendation = Field(..., description="Actionable recommendation")
    confidence_calibration: float = Field(..., description="Calibrated confidence adjustment delta")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Context metadata")
    evaluated_at: datetime = Field(default_factory=datetime.utcnow, description="Evaluation timestamp")


class EvaluateRequest(BaseModel):
    """Request DTO for POST /autoscientist/evaluate."""
    dataset_id: Optional[UUID] = Field(None, description="UUID of the dataset")
    hypothesis: Optional[ScientificHypothesis] = Field(None, description="Hypothesis object")
    plan: Optional[ExperimentPlan] = Field(None, description="Experiment plan object")
    execution_result: Optional[ExecutionResult] = Field(None, description="Execution result object")
    original_report: Optional[GenomeReportResponse] = Field(None, description="Baseline GenomeReportResponse JSON object")
    transformed_report: Optional[GenomeReportResponse] = Field(None, description="Mutated GenomeReportResponse JSON object")


class EvaluateResponse(BaseModel):
    """Response DTO for POST /autoscientist/evaluate."""
    dataset_id: Optional[UUID] = Field(None, description="UUID of the analyzed dataset")
    experiment_id: str = Field(..., description="ID of the underlying experiment")
    evaluation_report: EvaluationReport = Field(..., description="Complete EvaluationReport object")
    generated_at: datetime = Field(default_factory=datetime.utcnow, description="Response generation timestamp")
