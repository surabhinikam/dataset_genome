"""
services/autoscientist/experiment_models.py — Pydantic Schemas for Experiment Planning.

Defines ResourceEstimate, ExecutionStep, ValidationRuleItem, RollbackPlan,
ExperimentPlan, and REST API DTOs for POST /autoscientist/plan.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
from uuid import UUID
from pydantic import BaseModel, Field, ConfigDict

from schemas.intelligence import GenomeReportResponse
from services.autoscientist.hypothesis_models import ScientificHypothesis
from services.autoscientist.planning_constants import PlanningComplexity
from services.autoscientist.reasoning_models import ReasoningTrace


class ResourceEstimate(BaseModel):
    """Estimated computational resources for executing an ExperimentPlan."""
    estimated_runtime_seconds: float = Field(..., ge=0.0, description="Estimated execution runtime in seconds")
    estimated_memory_mb: float = Field(..., ge=0.0, description="Estimated peak RAM usage in Megabytes")
    estimated_disk_io_mb: float = Field(..., ge=0.0, description="Estimated Disk Read/Write IO in Megabytes")
    complexity_level: PlanningComplexity = Field(..., description="Overall planning complexity level: LOW, MEDIUM, or HIGH")


class ExecutionStep(BaseModel):
    """Single declarative step in an experiment execution sequence."""
    step_number: int = Field(..., ge=1, description="1-indexed sequence order")
    action: str = Field(..., description="Action verb name (e.g. LOAD_DATASET, APPLY_MUTATION, SAVE_VERSION)")
    target: Optional[str] = Field(None, description="Target column or artifact path")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Step parameters")
    description: str = Field(..., description="Human-readable step description")


class ValidationRuleItem(BaseModel):
    """Validation checklist item executed before or after a dataset mutation."""
    rule_id: str = Field(..., description="Unique rule identifier slug")
    rule_name: str = Field(..., description="Short descriptive rule title")
    target: str = Field(..., description="Target column or dataset component")
    check: str = Field(..., description="Type of validation check (e.g. COLUMN_EXISTS, NO_TARGET_LEAKAGE, DTYPE_MATCH)")
    description: str = Field(..., description="Detailed description of the check constraint")


class RollbackPlan(BaseModel):
    """Automated rollback strategy for reverting a dataset experiment."""
    is_supported: bool = Field(True, description="Whether automated rollback is supported")
    rollback_strategy: str = Field(..., description="Strategy name (e.g. RESTORE_FROM_BASELINE, RESTORE_COLUMN_BACKUP)")
    rollback_steps: List[ExecutionStep] = Field(default_factory=list, description="Ordered steps to execute for rollback")
    backup_required: bool = Field(True, description="Whether a pre-mutation backup artifact is required")
    description: str = Field(..., description="Detailed narrative explanation of the rollback procedure")


class ExperimentPlan(BaseModel):
    """
    Validated Experiment Plan generated by the Experiment Planner.
    
    Contains execution steps, validation rules, resource estimates, and automated
    rollback procedures without containing executable Python code.
    """
    model_config = ConfigDict(arbitrary_types_allowed=True)

    plan_id: str = Field(..., description="Unique slug for the experiment plan")
    hypothesis_id: str = Field(..., description="ID of the underlying ScientificHypothesis")
    transformation_type: str = Field(..., description="Recommended dataset transformation class name")
    target_columns: List[str] = Field(default_factory=list, description="Target dataset column names")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Resolved mutation parameters")
    execution_steps: List[ExecutionStep] = Field(..., description="Ordered execution steps")
    validation_rules: List[ValidationRuleItem] = Field(..., description="Pre and post mutation validation rules")
    dependencies: List[str] = Field(default_factory=list, description="Required software libraries")
    rollback_plan: RollbackPlan = Field(..., description="Automated rollback plan")
    estimated_runtime: float = Field(..., ge=0.0, description="Estimated execution runtime in seconds")
    estimated_memory: float = Field(..., ge=0.0, description="Estimated peak memory in Megabytes")
    expected_dataset_version: str = Field("v1.1.0", description="Expected output dataset version tag")
    resource_estimate: ResourceEstimate = Field(..., description="Resource estimate breakdown")
    execution_constraints: List[str] = Field(default_factory=list, description="Execution environment constraints")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Context metadata")
    created_at: datetime = Field(default_factory=datetime.utcnow, description="Creation timestamp")


class PlanRequest(BaseModel):
    """Request DTO for POST /autoscientist/plan."""
    dataset_id: Optional[UUID] = Field(None, description="UUID of an uploaded dataset")
    hypothesis: Optional[ScientificHypothesis] = Field(None, description="Direct ScientificHypothesis object payload")
    hypothesis_id: Optional[str] = Field(None, description="ID of an existing hypothesis")
    reasoning_trace: Optional[ReasoningTrace] = Field(None, description="Raw ReasoningTrace payload")
    report: Optional[GenomeReportResponse] = Field(None, description="Raw GenomeReportResponse JSON object")


class PlanResponse(BaseModel):
    """Response DTO for POST /autoscientist/plan."""
    dataset_id: Optional[UUID] = Field(None, description="UUID of the analyzed dataset")
    hypothesis_id: str = Field(..., description="ID of the underlying ScientificHypothesis")
    experiment_plan: ExperimentPlan = Field(..., description="Synthesized ExperimentPlan object")
    generated_at: datetime = Field(default_factory=datetime.utcnow, description="Response generation timestamp")
