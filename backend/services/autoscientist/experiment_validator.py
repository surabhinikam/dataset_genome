"""
services/autoscientist/experiment_validator.py — Experiment Plan Validator.

Validates complete ExperimentPlan domain objects, enforcing non-empty steps, valid target columns,
resource bounds, and zero cyclic/duplicate execution steps.
"""

from typing import List
from services.autoscientist.experiment_models import ExperimentPlan


class ExperimentValidator:
    """
    Validator for ExperimentPlan domain objects generated by the AutoScientist.
    """

    @classmethod
    def validate(cls, plan: ExperimentPlan) -> bool:
        """
        Validate an ExperimentPlan object.
        
        Raises ValueError if any field is malformed, missing, or invalid.
        Returns True on successful validation.
        """
        errors: List[str] = []

        if not plan.plan_id or not isinstance(plan.plan_id, str):
            errors.append("ExperimentPlan 'plan_id' must be a non-empty string.")

        if not plan.hypothesis_id or not isinstance(plan.hypothesis_id, str):
            errors.append("ExperimentPlan 'hypothesis_id' must be a non-empty string.")

        if not plan.transformation_type or not isinstance(plan.transformation_type, str):
            errors.append("ExperimentPlan 'transformation_type' must be a non-empty string.")

        if not isinstance(plan.execution_steps, list) or len(plan.execution_steps) == 0:
            errors.append("ExperimentPlan 'execution_steps' must be a non-empty list.")

        if not isinstance(plan.validation_rules, list) or len(plan.validation_rules) == 0:
            errors.append("ExperimentPlan 'validation_rules' must be a non-empty list.")

        if not plan.rollback_plan or not plan.rollback_plan.is_supported:
            errors.append("ExperimentPlan 'rollback_plan' must be valid and supported.")

        if plan.estimated_runtime < 0.0:
            errors.append(f"ExperimentPlan 'estimated_runtime' ({plan.estimated_runtime}) cannot be negative.")

        if plan.estimated_memory < 0.0:
            errors.append(f"ExperimentPlan 'estimated_memory' ({plan.estimated_memory}) cannot be negative.")

        # Check step sequence uniqueness & 1-indexed ordering
        step_nums = [s.step_number for s in plan.execution_steps]
        if len(step_nums) != len(set(step_nums)):
            errors.append("ExperimentPlan contains duplicate step_number values in execution_steps.")

        if errors:
            raise ValueError(f"ExperimentPlan validation failed with {len(errors)} error(s): " + "; ".join(errors))

        return True
