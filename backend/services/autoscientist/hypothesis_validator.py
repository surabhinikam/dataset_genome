"""
services/autoscientist/hypothesis_validator.py — Scientific Hypothesis Validator.

Validates complete ScientificHypothesis domain objects, enforcing positive metric deltas,
confidence bounds, non-empty parameter payloads, and scientific consistency.
"""

from typing import List
from services.autoscientist.hypothesis_constants import (
    MAX_PREDICTED_METRIC_DELTA,
    MIN_PREDICTED_METRIC_DELTA,
    RiskLevel,
)
from services.autoscientist.hypothesis_models import ScientificHypothesis


class HypothesisValidator:
    """
    Validator for ScientificHypothesis domain objects generated by the AutoScientist.
    """

    @classmethod
    def validate(cls, hypothesis: ScientificHypothesis) -> bool:
        """
        Validate a ScientificHypothesis object.
        
        Raises ValueError if any field is malformed, out of bounds, or scientifically inconsistent.
        Returns True on successful validation.
        """
        errors: List[str] = []

        if not hypothesis.id or not isinstance(hypothesis.id, str):
            errors.append("Hypothesis 'id' must be a non-empty string.")

        if not hypothesis.problem_id or not isinstance(hypothesis.problem_id, str):
            errors.append("Hypothesis 'problem_id' must be a non-empty string.")

        if not hypothesis.statement or not isinstance(hypothesis.statement, str):
            errors.append("Hypothesis 'statement' must be a non-empty string.")

        if not hypothesis.causal_mechanism or not isinstance(hypothesis.causal_mechanism, str):
            errors.append("Hypothesis 'causal_mechanism' must be a non-empty string.")

        if not hypothesis.transformation_type or not isinstance(hypothesis.transformation_type, str):
            errors.append("Hypothesis 'transformation_type' must be a non-empty string.")

        if not isinstance(hypothesis.proposed_parameters, dict) or len(hypothesis.proposed_parameters) == 0:
            errors.append("Hypothesis 'proposed_parameters' must be a non-empty dictionary.")

        # Metric delta bounds [0.001, 0.200]
        if not (MIN_PREDICTED_METRIC_DELTA <= hypothesis.predicted_metric_delta <= MAX_PREDICTED_METRIC_DELTA):
            errors.append(
                f"Hypothesis 'predicted_metric_delta' ({hypothesis.predicted_metric_delta:.4f}) "
                f"must be bounded in [{MIN_PREDICTED_METRIC_DELTA}, {MAX_PREDICTED_METRIC_DELTA}]."
            )

        # Confidence bounds [0.0, 1.0]
        if not (0.0 <= hypothesis.estimated_confidence <= 1.0):
            errors.append(
                f"Hypothesis 'estimated_confidence' ({hypothesis.estimated_confidence:.4f}) "
                f"must be bounded in [0.0, 1.0]."
            )

        if not isinstance(hypothesis.risk_level, RiskLevel):
            errors.append(f"Hypothesis 'risk_level' must be a valid RiskLevel enum instance.")

        if not isinstance(hypothesis.assumptions, list) or len(hypothesis.assumptions) == 0:
            errors.append("Hypothesis 'assumptions' must be a non-empty list of strings.")

        if not isinstance(hypothesis.constraints, list) or len(hypothesis.constraints) == 0:
            errors.append("Hypothesis 'constraints' must be a non-empty list of strings.")

        if errors:
            raise ValueError(f"ScientificHypothesis validation failed with {len(errors)} error(s): " + "; ".join(errors))

        return True
