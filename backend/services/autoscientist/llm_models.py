"""
services/autoscientist/llm_models.py — Pydantic Models for LLM Scientific Narrator.

Defines ExplanationTarget, ScientificExplanation, ExplainRequest, and ExplainResponse.
"""

from datetime import datetime
from enum import Enum
from typing import Any, Dict, Optional
from uuid import UUID
from pydantic import BaseModel, Field, ConfigDict

from services.autoscientist.evaluation_models import EvaluationReport
from services.autoscientist.experiment_models import ExperimentPlan
from services.autoscientist.hypothesis_models import ScientificHypothesis
from services.autoscientist.observation_models import ScientificObservation
from services.autoscientist.reasoning_models import ReasoningTrace
from services.autoscientist.research_models import ResearchNotebook


class ExplanationTarget(str, Enum):
    """Supported target domains for scientific explanation generation."""
    OBSERVATION = "OBSERVATION"
    REASONING = "REASONING"
    HYPOTHESIS = "HYPOTHESIS"
    PLAN = "PLAN"
    EVALUATION = "EVALUATION"
    NOTEBOOK = "NOTEBOOK"


class ScientificExplanation(BaseModel):
    """
    Standardized explanation output produced by the LLM Scientific Narrator.
    
    Contains multi-audience narrative summaries (Scientific, Executive, Technical, Business)
    and provenance metadata.
    """
    model_config = ConfigDict(arbitrary_types_allowed=True)

    scientific_summary: str = Field(..., description="Detailed scientific explanation of principles and mechanisms")
    executive_summary: str = Field(..., description="High-level C-suite executive summary")
    technical_summary: str = Field(..., description="Data engineering and algorithmic technical details")
    business_summary: str = Field(..., description="Business impact, ROI, and risk mitigation assessment")
    is_fallback: bool = Field(False, description="True if generated by deterministic fallback engine")
    model_used: str = Field("gemini-2.5-pro", description="LLM model or engine version used for explanation")
    generated_at: datetime = Field(default_factory=datetime.utcnow, description="Generation timestamp")


class ExplainRequest(BaseModel):
    """Request DTO for POST /autoscientist/explain."""
    target_type: ExplanationTarget = Field(ExplanationTarget.REASONING, description="Target domain for explanation")
    dataset_id: Optional[UUID] = Field(None, description="UUID of the analyzed dataset")
    observation: Optional[ScientificObservation] = Field(None, description="Observation payload")
    reasoning_trace: Optional[ReasoningTrace] = Field(None, description="ReasoningTrace payload")
    hypothesis: Optional[ScientificHypothesis] = Field(None, description="ScientificHypothesis payload")
    plan: Optional[ExperimentPlan] = Field(None, description="ExperimentPlan payload")
    evaluation_report: Optional[EvaluationReport] = Field(None, description="EvaluationReport payload")
    notebook: Optional[ResearchNotebook] = Field(None, description="ResearchNotebook payload")

    model_config = {
        "json_schema_extra": {
            "example": {
                "target_type": "REASONING",
                "dataset_id": "3fa85f64-5717-4562-b3fc-2c963f66afa6"
            }
        }
    }


class ExplainResponse(BaseModel):
    """Response DTO for POST /autoscientist/explain."""
    target_type: ExplanationTarget = Field(..., description="Target domain of the generated explanation")
    explanation: ScientificExplanation = Field(..., description="Structured explanation output")
    generated_at: datetime = Field(default_factory=datetime.utcnow, description="Response generation timestamp")
