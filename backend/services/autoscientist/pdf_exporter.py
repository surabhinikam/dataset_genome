"""
services/autoscientist/pdf_exporter.py — PDF Exporter for Research Notebooks.

Generates printable PDF report documents (HTML/Text payload bytes) from ResearchNotebook objects.
"""

import logging
from typing import Dict, Any
from services.autoscientist.markdown_exporter import MarkdownExporter
from services.autoscientist.research_models import ResearchNotebook

logger = logging.getLogger("dataset_genome.pdf_exporter")


class PDFExporter:
    """
    Exporter for rendering ResearchNotebook objects into PDF report payloads.
    """

    @classmethod
    def export_to_pdf_payload(cls, notebook: ResearchNotebook) -> Dict[str, Any]:
        """
        Export a ResearchNotebook as a structured PDF document payload.
        
        Returns dictionary containing HTML content, printable text, title, and metadata.
        """
        markdown_content = MarkdownExporter.export_to_markdown(notebook)
        
        # Build printable HTML representation
        html_lines = [
            "<!DOCTYPE html>",
            "<html>",
            "<head>",
            f"<title>{notebook.title}</title>",
            "<style>",
            "body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; line-height: 1.6; margin: 40px; color: #1f2937; }",
            "h1 { color: #1e3a8a; border-bottom: 2px solid #3b82f6; padding-bottom: 10px; }",
            "h2 { color: #1e40af; margin-top: 30px; }",
            "table { width: 100%; border-collapse: collapse; margin: 20px 0; }",
            "th, td { border: 1px solid #e5e7eb; padding: 10px; text-align: left; }",
            "th { background-color: #f3f4f6; }",
            "blockquote { background: #eff6ff; border-left: 4px solid #3b82f6; margin: 20px 0; padding: 15px; }",
            "code { background: #f3f4f6; padding: 2px 6px; border-radius: 4px; font-size: 0.9em; }",
            "pre { background: #1f2937; color: #f9fafb; padding: 15px; border-radius: 6px; overflow-x: auto; }",
            ".footer { margin-top: 50px; font-size: 0.85em; color: #6b7280; text-align: center; }",
            "</style>",
            "</head>",
            "<body>",
            f"<h1>{notebook.title}</h1>",
            f"<p><strong>Experiment ID:</strong> <code>{notebook.experiment_id}</code></p>",
            f"<p><strong>Overall Outcome:</strong> <code>{notebook.overall_outcome}</code></p>",
            f"<blockquote>{notebook.summary}</blockquote>",
            "<h2>Workflow Lineage Timeline</h2>",
            "<table>",
            "<thead><tr><th>Stage</th><th>Title</th><th>Dataset Version</th><th>Status</th></tr></thead>",
            "<tbody>",
        ]

        for entry in notebook.entries:
            html_lines.append(
                f"<tr><td><strong>{entry.stage.value}</strong></td><td>{entry.stage_title}</td>"
                f"<td><code>{entry.dataset_version}</code></td><td><code>{entry.status}</code></td></tr>"
            )

        html_lines.extend([
            "</tbody>",
            "</table>",
            "<div class='footer'>Report generated by Dataset Genome AutoScientist PDF Exporter</div>",
            "</body>",
            "</html>"
        ])

        html_str = "\n".join(html_lines)

        return {
            "notebook_id": notebook.notebook_id,
            "experiment_id": notebook.experiment_id,
            "title": notebook.title,
            "html_content": html_str,
            "markdown_content": markdown_content,
            "byte_size": len(html_str.encode("utf-8")),
            "format": "application/pdf-payload",
        }
