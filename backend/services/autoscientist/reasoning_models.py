"""
services/autoscientist/reasoning_models.py — Pydantic Schemas for Scientific Reasoning.

Defines ReasoningTrace, CausalReasoningTrace, and REST API DTOs for POST /autoscientist/reason.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
from uuid import UUID
from pydantic import BaseModel, Field, ConfigDict

from schemas.intelligence import GenomeReportResponse
from services.autoscientist.observation_constants import ObservationCategory
from services.autoscientist.ranking_models import RankedProblem


class ScientificMemoryInterface(BaseModel):
    """
    Interface stub for future Scientific Memory Engine integration.
    
    Allows querying past experimental recipes, successful mutations, and anti-patterns.
    """
    memory_enabled: bool = Field(False, description="Whether Scientific Memory integration is active")
    similar_past_experiments_count: int = Field(0, description="Count of relevant past experiments retrieved")
    historical_success_rate: float = Field(0.50, ge=0.0, le=1.0, description="Historical mutation success rate for issue type")
    blacklisted_mutations: List[str] = Field(default_factory=list, description="List of blacklisted mutation transforms")
    recommended_recipes: List[str] = Field(default_factory=list, description="Historical high-confidence experimental recipes")


class ReasoningTrace(BaseModel):
    """
    Structured Causal Reasoning Trace generated by the Reasoning Engine.
    
    Synthesizes causal mechanism inference, supporting evidence, assumptions,
    constraints, risks, and recommended transformation class for a prioritized problem.
    """
    model_config = ConfigDict(arbitrary_types_allowed=True)

    id: str = Field(..., description="Unique slug for the reasoning trace")
    problem_id: str = Field(..., description="ID of the underlying RankedProblem")
    category: ObservationCategory = Field(..., description="Profiler observation category")
    reasoning_summary: str = Field(..., description="Detailed natural language reasoning summary")
    inferred_mechanism: str = Field(..., description="Inferred causal flaw mechanism (e.g. MCAR/MAR, collinearity)")
    supporting_evidence: Dict[str, Any] = Field(default_factory=dict, description="Empirical evidence payload")
    recommended_transformation_class: str = Field(..., description="Recommended dataset transformation class name")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Calibrated reasoning confidence score")
    assumptions: List[str] = Field(default_factory=list, description="Explicit scientific assumptions")
    constraints: List[str] = Field(default_factory=list, description="Engineering and data invariants")
    risks: List[str] = Field(default_factory=list, description="Potential risks or side-effects of transformation")
    memory_insights: Optional[ScientificMemoryInterface] = Field(None, description="Memory insights from Scientific Memory Engine")
    generated_at: datetime = Field(default_factory=datetime.utcnow, description="Generation timestamp")


class ReasonRequest(BaseModel):
    """Request DTO for POST /autoscientist/reason."""
    dataset_id: Optional[UUID] = Field(None, description="UUID of an uploaded dataset")
    ranked_problem: Optional[RankedProblem] = Field(None, description="Direct RankedProblem payload")
    prioritized_problem: Optional[RankedProblem] = Field(None, description="Alias for ranked_problem payload")
    report: Optional[GenomeReportResponse] = Field(None, description="Raw GenomeReportResponse JSON object")
    memory_stub: Optional[ScientificMemoryInterface] = Field(None, description="Optional memory interface payload")


class ReasonResponse(BaseModel):
    """Response DTO for POST /autoscientist/reason."""
    dataset_id: Optional[UUID] = Field(None, description="UUID of the analyzed dataset")
    problem_id: str = Field(..., description="ID of the reasoned problem")
    reasoning_trace: ReasoningTrace = Field(..., description="Complete CausalReasoningTrace object")
    generated_at: datetime = Field(default_factory=datetime.utcnow, description="Response generation timestamp")
