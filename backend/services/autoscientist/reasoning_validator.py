"""
services/autoscientist/reasoning_validator.py — Reasoning Trace Validator.

Validates complete ReasoningTrace domain objects, enforcing non-empty fields,
bounded confidence scores, and structured assumptions/constraints/risks.
"""

from typing import List
from services.autoscientist.reasoning_models import ReasoningTrace


class ReasoningValidator:
    """
    Validator for Causal Reasoning Traces generated by the AutoScientist Reasoning Engine.
    """

    @classmethod
    def validate(cls, trace: ReasoningTrace) -> bool:
        """
        Validate a ReasoningTrace object.
        
        Raises ValueError if any field is malformed or incomplete.
        Returns True on successful validation.
        """
        errors: List[str] = []

        if not trace.id or not isinstance(trace.id, str):
            errors.append("ReasoningTrace 'id' must be a non-empty string.")

        if not trace.problem_id or not isinstance(trace.problem_id, str):
            errors.append("ReasoningTrace 'problem_id' must be a non-empty string.")

        if not trace.reasoning_summary or not isinstance(trace.reasoning_summary, str):
            errors.append("ReasoningTrace 'reasoning_summary' must be a non-empty string.")

        if not trace.inferred_mechanism or not isinstance(trace.inferred_mechanism, str):
            errors.append("ReasoningTrace 'inferred_mechanism' must be a non-empty string.")

        if not trace.recommended_transformation_class or not isinstance(trace.recommended_transformation_class, str):
            errors.append("ReasoningTrace 'recommended_transformation_class' must be a non-empty string.")

        if not (0.0 <= trace.confidence <= 1.0):
            errors.append(f"ReasoningTrace 'confidence' ({trace.confidence}) must be bounded in [0.0, 1.0].")

        if not isinstance(trace.assumptions, list) or len(trace.assumptions) == 0:
            errors.append("ReasoningTrace 'assumptions' must be a non-empty list of strings.")

        if not isinstance(trace.constraints, list) or len(trace.constraints) == 0:
            errors.append("ReasoningTrace 'constraints' must be a non-empty list of strings.")

        if not isinstance(trace.risks, list) or len(trace.risks) == 0:
            errors.append("ReasoningTrace 'risks' must be a non-empty list of strings.")

        if errors:
            raise ValueError(f"ReasoningTrace validation failed with {len(errors)} error(s): " + "; ".join(errors))

        return True
